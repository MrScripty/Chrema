import { assertWorkflowResultIdentity } from './workflow-validation-contract.mjs';

const contract = {
  id: 'workflow-admission-receipt.v1', channel: 'code-owned-result', unknownFields: 'retained',
  context: 'Trusted receipt constructed inside the admission transaction. Success is established only after commit and durable receipt/run state, not by reaching the handler. A conflict may defer admission to revision without a receipt; that is not a successful merge. Additional audit fields are retained.',
  fields: [
    { name: 'admissionId', type: 'nonempty receipt identity' },
    { name: 'runId', type: 'current run identity' },
    { name: 'workflowVersionId', type: 'pinned workflow identity' },
    { name: 'manifestHash', type: 'exact compiled lowercase SHA-256' },
    { name: 'admittedBy', type: 'nonempty actor identity' },
    { name: 'admittedAt', type: 'ISO UTC timestamp' },
    { name: 'commandResults', type: 'array; exactly one result per manifest command', fields: [
      { name: 'commandId', type: 'manifest command identity' },
      { name: 'commandType', type: 'matching manifest command type' },
      { name: 'result', type: 'domain-owned result payload' },
      { name: 'resultHash', type: 'lowercase SHA-256; generated by admission code' },
    ] },
    { name: 'summary', type: 'object', fields: [
      { name: 'commandCount', type: 'integer equal to commandResults length' },
      { name: 'admittedDomainIds', type: 'array of distinct nonempty strings' },
    ] },
  ],
};

export function describeWorkflowAdmissionReceipt() { return structuredClone(contract); }

/** Run inside the transaction before committing a newly constructed receipt. */
export function validateWorkflowAdmissionReceipt(receipt, manifest) {
  assertWorkflowResultIdentity(receipt, manifest, 'Admission receipt');
  const text = value => typeof value === 'string' && value.trim().length > 0;
  if (!text(receipt.admissionId) || !text(receipt.admittedBy)
    || !text(receipt.workflowVersionId) || receipt.workflowVersionId !== manifest.workflowVersionId
    || typeof receipt.admittedAt !== 'string' || !Number.isFinite(Date.parse(receipt.admittedAt))
    || new Date(receipt.admittedAt).toISOString() !== receipt.admittedAt) {
    throw new TypeError('Admission receipt requires valid identities and an ISO UTC timestamp.');
  }
  if (!Array.isArray(manifest.commands) || !Array.isArray(receipt.commandResults)) {
    throw new TypeError('Admission receipt requires manifest command results.');
  }
  const expected = new Map(manifest.commands.map(command => [command.commandId, command.commandType]));
  const seen = new Set();
  for (const result of receipt.commandResults) {
    if (!text(result?.commandId) || !expected.has(result.commandId) || seen.has(result.commandId)
      || result.commandType !== expected.get(result.commandId) || !Object.hasOwn(result, 'result')
      || !/^[a-f0-9]{64}$/.test(result.resultHash ?? '')) {
      throw new TypeError('Admission receipt result must match one unique manifest command.');
    }
    seen.add(result.commandId);
  }
  if (expected.size !== manifest.commands.length || seen.size !== expected.size
    || receipt.summary?.commandCount !== seen.size
    || !Array.isArray(receipt.summary?.admittedDomainIds)
    || !receipt.summary.admittedDomainIds.every(text)
    || new Set(receipt.summary.admittedDomainIds).size !== receipt.summary.admittedDomainIds.length) {
    throw new TypeError('Admission receipt requires complete command results and a consistent summary.');
  }
  return receipt;
}
